function api($method, $path, $user, $body=null, $expected=200) {
    $headers=['Accept: application/json','Content-Type: application/json'];
    if ($user) $headers[]='Authorization: Bearer '.Tymon\JWTAuth\Facades\JWTAuth::fromUser($user);
    $curl=curl_init('http://127.0.0.1:18084/api/'.$path);
    curl_setopt_array($curl,[CURLOPT_CUSTOMREQUEST=>$method,CURLOPT_RETURNTRANSFER=>true,CURLOPT_HTTPHEADER=>$headers,CURLOPT_TIMEOUT=>20]);
    if ($body!==null) curl_setopt($curl,CURLOPT_POSTFIELDS,json_encode($body));
    $raw=curl_exec($curl); $status=curl_getinfo($curl,CURLINFO_HTTP_CODE); curl_close($curl);
    if ($status!==$expected) throw new RuntimeException("$path expected $expected got $status $raw");
    $json=json_decode($raw,true); return $json['data']??$json;
}
